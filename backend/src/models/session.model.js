// Session model — represents an authenticated login session.
//
// Phase 14 design notes (see docs/AUTH_SESSION_MANAGEMENT.md):
//
// 1. Each successful login creates a Session document. The document
//    binds a User to:
//      - a refresh token (stored as SHA-256 hash, never plaintext),
//      - a token family identifier (so we can revoke the entire
//        family when reuse is detected),
//      - an expiry timestamp,
//      - the client that initiated the session (userAgent, IP —
//        optional, only when available, with a retention policy).
//
// 2. The access token is a JWT carrying the session _id in the
//    `jti` claim. The access token itself is NOT stored — JWTs are
//    stateless. To revoke an access token BEFORE its natural
//    expiry, see docs/AUTH_SESSION_MANAGEMENT.md §6 (Plan A vs
//    Plan B). Plan A is implemented: access tokens stay valid
//    until `exp`; logout revokes the refresh session, blocking
//    future token issuance. Plan B (server-side access-token
//    denylist) is intentionally OUT OF SCOPE.
//
// 3. `tokenHash` is the SHA-256 hex of the opaque refresh token
//    (32 random bytes → 64 hex chars). SHA-256 (not bcrypt) is
//    appropriate here because the input has 256 bits of entropy
//    already — bcrypt is for low-entropy secrets (passwords).
//    A unique index on tokenHash lets us O(log n) look up by token
//    and prevents collisions.
//
// 4. `familyId` groups refresh tokens that were issued by the same
//    chain of rotations. If a refresh token is presented AFTER it
//    was already used or revoked, we treat this as token theft
//    and revoke the entire family. This is the standard
//    refresh-token-reuse-detection pattern.
//
// 5. `expiresAt` carries a TTL index so MongoDB can clean up
//    expired sessions automatically. We use a derived index
//    (NOT the field itself) so that a malformed document without
//    `expiresAt` is NOT deleted silently — MongoDB only deletes
//    documents that have the indexed field set and the time has
//    passed.
//
// 6. We do NOT add an index that would let a leaked token bypass
//    expiry. The only way to use a session is through `findOne`
//    by `tokenHash` AND the `revokedAt === null` AND
//    `expiresAt > now` checks at refresh time.

import mongoose from 'mongoose';
import { createHash, randomUUID } from 'node:crypto';

const { Schema } = mongoose;

export const SESSION_REVOKE_REASONS = Object.freeze([
  'logout',
  'refresh_rotation',
  'reuse_detected',
  'user_status_changed',
  'user_logout_all',
  'admin_revoke',
]);

/**
 * Hash a refresh token for at-rest storage. The input is a
 * 64-char hex string (32 random bytes) generated by
 * `generateRefreshToken()` in src/services/auth.service.js.
 *
 * The hash is keyed — it is not feasible to recover the plaintext
 * from the stored hash.
 */
export function hashRefreshToken(token) {
  if (typeof token !== 'string' || token.length === 0) {
    throw new Error('hashRefreshToken requires a non-empty string');
  }
  return createHash('sha256').update(token, 'utf8').digest('hex');
}

const sessionSchema = new Schema(
  {
    // Reference to User. NOT cascading-deleted at the schema level
    // — session cleanup is the auth service's responsibility, and
    // tests/seed scripts sometimes need to clean up in a specific
    // order.
    userId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'userId is required'],
      index: true,
    },

    // SHA-256 hex of the refresh token. NEVER plaintext.
    // Unique so a collision is impossible and so the lookup is
    // O(log n).
    tokenHash: {
      type: String,
      required: [true, 'tokenHash is required'],
      unique: true,
    },

    // UUID grouping rotation chains. When reuse is detected, ALL
    // sessions in the same family are revoked. A new family is
    // started at every successful login.
    familyId: {
      type: String,
      required: [true, 'familyId is required'],
      index: true,
    },

    // Wall-clock expiry for the refresh token. Independent of
    // the access token's JWT exp claim.
    expiresAt: {
      type: Date,
      required: [true, 'expiresAt is required'],
    },

    // When set, the session is revoked and any further use of the
    // token (including reuse detection) is rejected. The reason
    // is captured for audit / debugging.
    revokedAt: {
      type: Date,
      default: null,
    },
    revokedReason: {
      type: String,
      enum: {
        values: [...SESSION_REVOKE_REASONS, null],
        message: 'revokedReason must be a known reason or null',
      },
      default: null,
    },

    // Optional client context. Limited-size, never logged in full,
    // and used only for user-facing session list. NOT a security
    // signal.
    userAgent: {
      type: String,
      default: null,
      maxlength: [512, 'userAgent too long'],
    },
    ip: {
      type: String,
      default: null,
      maxlength: [64, 'ip too long'],
    },

    // Last time the refresh token was successfully exchanged for
    // a new pair. Used for "active session" detection and audit.
    lastUsedAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

// Compound index for "list my active sessions" queries.
sessionSchema.index({ userId: 1, revokedAt: 1, expiresAt: 1 });

// TTL index — MongoDB removes documents whose `expiresAt` has
// passed. `expireAfterSeconds: 0` means "expire AT `expiresAt`,
// not after a delay". Documents WITHOUT an `expiresAt` field are
// not removed by this index.
//
// We rely on application logic (not the TTL) to actually reject
// expired tokens — the TTL is a cleanup convenience, not a
// security control.
sessionSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });

// Sanitize JSON output. We never want to expose `tokenHash` to
// the client (it is the credential). Field-level only — the
// service layer is also responsible for projecting the right
// shape to clients.
function sanitizeSession(doc, ret) {
  if (ret && Object.prototype.hasOwnProperty.call(ret, 'tokenHash')) {
    delete ret.tokenHash;
  }
  if (ret && Object.prototype.hasOwnProperty.call(ret, '__v')) {
    delete ret.__v;
  }
  return ret;
}

sessionSchema.set('toJSON', {
  virtuals: true,
  versionKey: false,
  transform: sanitizeSession,
});

sessionSchema.set('toObject', {
  virtuals: true,
  versionKey: false,
  transform: sanitizeSession,
});

// Static helper — generate a new family id. UUID v4 is sufficient;
// these are not secrets.
sessionSchema.statics.newFamilyId = function newFamilyId() {
  return randomUUID();
};

const Session = mongoose.model('Session', sessionSchema);

export default Session;
